// Extract reusable WebP skins from the approved Sources sheets.
import {readFileSync,writeFileSync,mkdirSync,readdirSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const root=resolve(import.meta.dirname,'..'),source=resolve(process.argv[2]||'../optimized_assets/Sources');
const dir=join(root,'studio/assets/legend-v12');mkdirSync(dir,{recursive:true});
const magick=(...args)=>execFileSync('magick',args);
if(process.argv[3])magick(resolve(process.argv[3]),'-quality','95',join(dir,'hud-empty-master.webp'));
const crop=(file,rect,name)=>magick(file,'-crop',rect,'+repage','-quality','95',join(dir,name+'.webp'));
const frames=join(source,'Legend Ball X1000 transparent asset sheet(1).webp');
crop(frames,'820x176+150+474','win-frame');
crop(frames,'914x114+105+652','scatter-banner');
crop(frames,'1082x590+20+772','reel-frame');
crop(join(source,'01_background.webp'),'852x206+0+1640','lava-ground');
const hud=join(dir,'hud-empty-master.webp');
for(const [name,rect] of [['buy-frame','940x282+90+54'],['bonus-frame','940x252+90+338'],['credit-frame','940x242+90+590'],['bet-frame','940x226+90+832']])crop(hud,rect,name);
const p=JSON.parse(readFileSync(join(root,'studio/project.json')));
const layer=id=>p.layers.find(l=>l.id===id);
for(const id of ['winbanner','reelframe','buybtn','antebtn','creditpanel','betpanel'])layer(id).asset='legend-v12/'+({winbanner:'win',reelframe:'reel',buybtn:'buy',antebtn:'bonus',creditpanel:'credit',betpanel:'bet'}[id])+'-frame.webp';
Object.assign(layer('sky'),{x:-16,y:-16,w:1112,h:1952});
Object.assign(layer('logo'),{x:260,y:125,w:695,h:285});
Object.assign(layer('winbanner'),{x:190,y:418,w:790,h:154});
Object.assign(layer('winamount'),{x:350,y:456,w:470,h:77});
Object.assign(layer('bonuscopy'),{visible:false});
p.layers=p.layers.filter(l=>!['scatterbanner','lavaground'].includes(l.id));
p.layers.push({id:'scatterbanner',name:'Gold Scatter banner',kind:'image',asset:'legend-v12/scatter-banner.webp',x:60,y:560,w:960,h:100,z:10,rotate:0,opacity:100,visible:true,locked:false});
p.layers.push({id:'lavaground',name:'Lava foreground',kind:'image',asset:'legend-v12/lava-ground.webp',x:-16,y:1651,w:1112,h:269,z:1,rotate:0,opacity:100,visible:true,locked:false,parallax:{x:2,y:0}});
Object.assign(layer('reelframe'),{x:20,y:615,w:1040,h:832,z:13});
Object.assign(layer('reels'),{x:66,y:642,w:948,h:790});
Object.assign(layer('buybtn'),{x:22,y:1450,w:502,h:125});
Object.assign(layer('antebtn'),{x:555,y:1450,w:503,h:125});
Object.assign(layer('creditpanel'),{x:22,y:1580,w:502,h:120});
Object.assign(layer('credits'),{x:65,y:1597,w:410,h:82});
Object.assign(layer('betpanel'),{x:555,y:1580,w:503,h:120});
Object.assign(layer('betlabel'),{x:681,y:1597,w:250,h:82,locked:true});
Object.assign(layer('minusbtn'),{x:576,y:1590,w:100,h:100,locked:true});
Object.assign(layer('plusbtn'),{x:936,y:1590,w:100,h:100,locked:true});
for(const id of ['minusbtn','plusbtn'])delete layer(id).asset;
for(const id of ['soundbtn','provider'])Object.assign(layer(id),{visible:false,locked:true});
layer('provider').text='';
Object.assign(layer('spinbutton'),{x:420,y:1700,w:240,h:220});
Object.assign(layer('autobtn'),{x:205,y:1748,w:155,h:155});
Object.assign(layer('turbobtn'),{x:720,y:1748,w:155,h:155});
Object.assign(layer('menubtn'),{x:15,y:1758,w:150,h:150});
Object.assign(layer('infobtn'),{x:915,y:1758,w:150,h:150});
// Only the design preview arrangement changes, never the outcome weights.
p.grid[29]='scatter';
p.ui={...p.ui,layout:'unified-v12'};
writeFileSync(join(root,'studio/project.json'),JSON.stringify(p,null,2)+'\n');
const old=JSON.parse(readFileSync(join(root,'studio/assets/legend-v10/manifest.json'))).assets;
const replaced=new Set(['win-frame','reel-frame','buy-frame','bonus-frame','credit-frame','bet-frame','minus','plus','sound']);
const assets=readdirSync(dir).filter(f=>f.endsWith('.webp')&&!f.includes('master')).map(file=>{
 const bytes=readFileSync(join(dir,file)),[w,h]=execFileSync('magick',['identify','-format','%w %h',join(dir,file)],{encoding:'utf8'}).split(' ').map(Number);
 return{id:'v12-'+file.slice(0,-5),path:'legend-v12/'+file,label:file.slice(0,-5).replaceAll('-',' '),kind:'image',group:'LEGEND BALL V12',naturalWidth:w,naturalHeight:h,bytes:bytes.length,sha256:createHash('sha256').update(bytes).digest('hex')};
});
const all=[...old.filter(a=>!replaced.has(a.id)),...assets];
writeFileSync(join(dir,'manifest.json'),JSON.stringify({version:12,assets:all},null,2)+'\n');
writeFileSync(join(dir,'catalog.js'),'window.LEGEND_V12_ASSET_LIBRARY='+JSON.stringify(assets)+';\n');
console.log(JSON.stringify({newSkins:assets.length,layers:p.layers.length}));
